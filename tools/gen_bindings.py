#!/usr/bin/env python3
"""Generates src/main/java/dev/ingot/nativ/Mtl.java from native/include/ingot.h.

Every `INGOT_EXPORT <ret> <name>(<params>);` declaration becomes a static method on Mtl that invokes a cached
downcall handle. Pointers (any type containing '*') are passed as Java longs. A declaration preceded by a line
consisting only of `INGOT_HOT` is linked with Linker.Option.critical(false): it must not block or call back into Java.

Run: python3 tools/gen_bindings.py   (the Gradle build also checks the output is current)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = ROOT / "native" / "include" / "ingot.h"
OUT = ROOT / "src" / "main" / "java" / "dev" / "ingot" / "nativ" / "Mtl.java"

C_TO_JAVA = {
    "void": ("void", None),
    "int8_t": ("byte", "JAVA_BYTE"),
    "uint8_t": ("byte", "JAVA_BYTE"),
    "int16_t": ("short", "JAVA_SHORT"),
    "uint16_t": ("short", "JAVA_SHORT"),
    "int32_t": ("int", "JAVA_INT"),
    "uint32_t": ("int", "JAVA_INT"),
    "int": ("int", "JAVA_INT"),
    "int64_t": ("long", "JAVA_LONG"),
    "uint64_t": ("long", "JAVA_LONG"),
    "size_t": ("long", "JAVA_LONG"),
    "float": ("float", "JAVA_FLOAT"),
    "double": ("double", "JAVA_DOUBLE"),
    "bool": ("boolean", "JAVA_BOOLEAN"),
}

DECL = re.compile(r"INGOT_EXPORT\s+(?P<ret>[\w\s\*]+?)\s*(?P<name>ingot_\w+)\s*\((?P<params>[^)]*)\)\s*;", re.S)
CONST = re.compile(r"^#define\s+(INGOT_[A-Z0-9_]+)\s+\(?\s*(-?(?:0x[0-9a-fA-F]+|\d+))u?\s*\)?\s*(?://.*)?$", re.M)


def map_type(ctype):
    ctype = " ".join(ctype.replace("const ", "").split())
    if "*" in ctype:
        return ("long", "JAVA_LONG")
    if ctype not in C_TO_JAVA:
        sys.exit(f"gen_bindings: unsupported C type '{ctype}'")
    return C_TO_JAVA[ctype]


def split_param(param):
    param = param.strip()
    m = re.match(r"(?P<type>.*?[\s\*])(?P<name>\w+)$", param)
    if not m:
        sys.exit(f"gen_bindings: cannot parse parameter '{param}'")
    return m.group("type").strip(), m.group("name")


def main():
    text = HEADER.read_text()
    lines = text.splitlines()

    hot = set()
    for i, line in enumerate(lines):
        if line.strip() == "INGOT_HOT":
            # A line holding only the marker applies to the next exported declaration.
            for nxt in lines[i + 1:]:
                m = re.search(r"INGOT_EXPORT\s+[\w\s\*]+?(ingot_\w+)\s*\(", nxt)
                if m:
                    hot.add(m.group(1))
                    break

    consts = [(n, v) for n, v in CONST.findall(text) if n not in ("INGOT_EXPORT", "INGOT_HOT")]

    funcs = []
    for m in DECL.finditer(text):
        ret = m.group("ret").strip()
        name = m.group("name")
        params = m.group("params").strip()
        plist = [] if params in ("", "void") else [split_param(p) for p in params.split(",")]
        funcs.append((ret, name, plist))

    out = []
    out.append("// GENERATED by tools/gen_bindings.py from native/include/ingot.h. Do not edit by hand.")
    out.append("package dev.ingot.nativ;")
    out.append("")
    out.append("import java.lang.foreign.FunctionDescriptor;")
    out.append("import java.lang.foreign.Linker;")
    out.append("import java.lang.foreign.SymbolLookup;")
    out.append("import java.lang.invoke.MethodHandle;")
    out.append("")
    out.append("import static java.lang.foreign.ValueLayout.*;")
    out.append("")
    out.append("@SuppressWarnings({\"unused\", \"SpellCheckingInspection\"})")
    out.append("public final class Mtl {")
    out.append("\tprivate Mtl() {")
    out.append("\t}")
    out.append("")
    for n, v in consts:
        java_name = n[len("INGOT_"):]
        out.append(f"\tpublic static final int {java_name} = {v};")
    out.append("")
    out.append("\tprivate static final Linker LINKER = Linker.nativeLinker();")
    out.append("\tprivate static final SymbolLookup LIB = NativeLibrary.lookup();")
    out.append("")
    out.append("\tprivate static MethodHandle link(String name, FunctionDescriptor desc, boolean hot) {")
    out.append("\t\tvar symbol = LIB.find(name).orElseThrow(() -> new UnsatisfiedLinkError(\"libingot is missing \" + name));")
    out.append("\t\treturn hot ? LINKER.downcallHandle(symbol, desc, Linker.Option.critical(false)) : LINKER.downcallHandle(symbol, desc);")
    out.append("\t}")
    out.append("")
    out.append("\tprivate static RuntimeException rethrow(Throwable t) {")
    out.append("\t\tif (t instanceof RuntimeException r) return r;")
    out.append("\t\tif (t instanceof Error e) throw e;")
    out.append("\t\treturn new IllegalStateException(t);")
    out.append("\t}")

    for ret, name, plist in funcs:
        jret, lret = map_type(ret)
        jparams = [(map_type(t), n) for t, n in plist]
        args_layouts = ", ".join(l for (_, l), _ in jparams)
        if lret is None:
            desc = f"FunctionDescriptor.ofVoid({args_layouts})"
        else:
            desc = f"FunctionDescriptor.of({lret}{', ' if args_layouts else ''}{args_layouts})"
        handle = "H_" + name[len("ingot_"):].upper()
        java_name = re.sub(r"_([a-z0-9])", lambda mm: mm.group(1).upper(), name[len("ingot_"):])
        sig = ", ".join(f"{jt} {pn}" for (jt, _), pn in jparams)
        call = ", ".join(pn for _, pn in jparams)
        out.append("")
        out.append(f"\tprivate static final MethodHandle {handle} = link(\"{name}\", {desc}, {str(name in hot).lower()});")
        out.append("")
        out.append(f"\tpublic static {jret} {java_name}({sig}) {{")
        out.append("\t\ttry {")
        if jret == "void":
            out.append(f"\t\t\t{handle}.invokeExact({call});")
        else:
            out.append(f"\t\t\treturn ({jret}) {handle}.invokeExact({call});")
        out.append("\t\t} catch (Throwable t) {")
        out.append("\t\t\tthrow rethrow(t);")
        out.append("\t\t}")
        out.append("\t}")

    out.append("}")
    out.append("")
    result = "\n".join(out)

    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != result:
            sys.exit("gen_bindings: Mtl.java is out of date; run python3 tools/gen_bindings.py")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(result)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(funcs)} functions, {len(consts)} constants, {len(hot)} hot)")


if __name__ == "__main__":
    main()
